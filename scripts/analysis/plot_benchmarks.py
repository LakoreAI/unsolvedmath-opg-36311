#!/usr/bin/env python3
"""Render the subset-sum measurements to vector figures for the paper.

Reads `bench.csv` / `memory.csv` produced by `scripts/analysis/benchmark.py`
and writes `fig_runtime.pdf`, `fig_states.pdf`, `fig_memory.pdf` next to the
paper in `docs/reports/`.

Requires matplotlib (a dev dependency):

    uv run python scripts/analysis/plot_benchmarks.py
"""

import argparse
import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = REPO_ROOT / "docs" / "analysis" / "2026-10-03" / "subset-sum"
FIGURE_DIR = REPO_ROOT / "docs" / "reports" / "baselines" / "figures"
TABLE_DIR = REPO_ROOT / "docs" / "reports" / "baselines" / "tables"

LABELS = {
    "brute": "brute force",
    "dp": "signed DP",
    "mitm": "meet-in-the-middle",
    "ss": "Schroeppel-Shamir",
}


def read_csv(path):
    with path.open() as fh:
        return list(csv.DictReader(fh))


def series(rows, family, metric, algorithm):
    pts = sorted(
        (int(r["n"]), float(r[metric]))
        for r in rows
        if r.get("family") == family and r["algorithm"] == algorithm
    )
    return [p[0] for p in pts], [p[1] for p in pts]


def style(ax):
    ax.grid(True, which="both", ls=":", lw=0.4, alpha=0.6)
    ax.set_xlabel("number of entries $n$")


def plot_runtime(bench, out):
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.7))
    for ax, family in zip(axes, ("signed_small", "wide_random")):
        for alg in ("brute", "dp", "mitm", "ss"):
            xs, ys = series(bench, family, "seconds", alg)
            if xs:
                ax.plot(xs, ys, marker="o", ms=2.5, lw=1.1, label=LABELS[alg])
        ax.set_yscale("log")
        ax.set_title(family.replace("_", " "))
        style(ax)
        ax.set_ylabel("seconds (best of runs)")
        ax.legend(fontsize=6, frameon=False)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def plot_states(bench, out):
    fig, ax = plt.subplots(figsize=(3.6, 2.7))
    for alg, color in (("mitm", "tab:blue"), ("ss", "tab:orange")):
        xs, ys = series(bench, "wide_random", "states", alg)
        ax.plot(xs, ys, marker="o", ms=3, lw=1.2, color=color, label=LABELS[alg])
    ref_n = list(range(8, 37, 4))
    ax.plot(ref_n, [2 ** (n / 2) for n in ref_n], "k--", lw=0.8, label="$2^{n/2}$")
    ax.plot(ref_n, [2 ** (n / 4) for n in ref_n], "k:", lw=0.8, label="$2^{n/4}$")
    ax.set_yscale("log")
    style(ax)
    ax.set_ylabel("work units (log scale)")
    ax.legend(fontsize=6, frameon=False)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def plot_memory(mem, out):
    fig, ax = plt.subplots(figsize=(3.6, 2.7))
    for alg, color in (("mitm", "tab:blue"), ("ss", "tab:orange")):
        xs, ys = series(mem, "signed_small", "peak_kib", alg)
        ax.plot(xs, ys, marker="o", ms=3, lw=1.2, color=color, label=LABELS[alg])
    ref_n = list(range(8, 33, 4))
    ax.plot(
        ref_n, [0.3 * 2 ** (n / 2) for n in ref_n], "k--", lw=0.8, label="$2^{n/2}$"
    )
    ax.plot(ref_n, [2.5 * 2 ** (n / 4) for n in ref_n], "k:", lw=0.8, label="$2^{n/4}$")
    ax.set_yscale("log")
    style(ax)
    ax.set_ylabel("peak memory (KiB, log scale)")
    ax.legend(fontsize=6, frameon=False)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def lookup(rows, family, algorithm, metric):
    return {
        int(r["n"]): float(r[metric])
        for r in rows
        if r.get("family") == family and r["algorithm"] == algorithm
    }


def write_latex(bench, mem, out):
    """Emit the measurement tables as LaTeX, straight from the CSV data."""
    runtime_ms = {}
    ns = set()
    for family in ("signed_small", "wide_random"):
        for alg in ("dp", "mitm", "ss"):
            runtime_ms[(family, alg)] = {
                n: 1000.0 * v for n, v in lookup(bench, family, alg, "seconds").items()
            }
            ns |= set(runtime_ms[(family, alg)])
    peak = {
        alg: lookup(mem, "signed_small", alg, "peak_kib")
        for alg in ("dp", "mitm", "ss")
    }

    def cell(value):
        return "--" if value is None else f"{value:.2f}"

    lines = [
        "% Generated by scripts/analysis/plot_benchmarks.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Runtime in milliseconds (best of the timed runs) on infeasible",
        r"instances; ``--'' marks a configuration not run. Bounded values are",
        r"even integers in $[-100,100]$, wide values in $[-2^{40},2^{40}]$; the",
        r"odd target forces each solver to run to completion.}",
        r"\label{tab:runtime}",
        r"\begin{tabular}{r" + "r" * 5 + "}",
        r"\toprule",
        r"& \multicolumn{3}{c}{bounded values} & \multicolumn{2}{c}{wide values} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}",
        r"$n$ & DP & MITM & Schroeppel--Shamir & MITM & Schroeppel--Shamir \\",
        r"\midrule",
    ]
    for n in sorted(ns):
        row = [
            str(n),
            cell(runtime_ms[("signed_small", "dp")].get(n)),
            cell(runtime_ms[("signed_small", "mitm")].get(n)),
            cell(runtime_ms[("signed_small", "ss")].get(n)),
            cell(runtime_ms[("wide_random", "mitm")].get(n)),
            cell(runtime_ms[("wide_random", "ss")].get(n)),
        ]
        lines.append(" & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    lines += [
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Peak traced memory in KiB on bounded-value instances (lower is",
        r"better). MITM grows like $2^{n/2}$; Schroeppel--Shamir like $2^{n/4}$.}",
        r"\label{tab:memory}",
        r"\begin{tabular}{rrrr}",
        r"\toprule",
        r"$n$ & DP & MITM & Schroeppel--Shamir \\",
        r"\midrule",
    ]
    for n in sorted(peak["mitm"]):
        row = [str(n)] + [cell(peak[alg].get(n)) for alg in ("dp", "mitm", "ss")]
        lines.append(" & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    (out / "measured_tables.tex").write_text("\n".join(lines) + "\n")
    print(f"{out / 'measured_tables.tex'}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DATA_DIR)
    parser.add_argument("--figures", type=Path, default=FIGURE_DIR)
    parser.add_argument("--tables", type=Path, default=TABLE_DIR)
    args = parser.parse_args()

    bench = read_csv(args.data / "bench.csv")
    mem = read_csv(args.data / "memory.csv")
    args.figures.mkdir(parents=True, exist_ok=True)
    args.tables.mkdir(parents=True, exist_ok=True)
    plot_runtime(bench, args.figures / "fig_runtime.pdf")
    plot_states(bench, args.figures / "fig_states.pdf")
    plot_memory(mem, args.figures / "fig_memory.pdf")
    write_latex(bench, mem, args.tables)
    for name in ("fig_runtime.pdf", "fig_states.pdf", "fig_memory.pdf"):
        path = args.figures / name
        print(f"{path} ({path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
